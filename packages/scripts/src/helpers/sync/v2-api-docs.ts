import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { getRootDir, writeIfChanged } from '../misc.js';

/*
 * Writes the generated tables into the v2 API doc. The tables come from the
 * v2 route registry, which lives in teraslice. Scripts doesn't depend on
 * teraslice, so this loads the generator from teraslice's dist by path,
 * after checking that dist is built and up to date.
 */

export const v2ApiDocPath = 'docs/management-apis/endpoints-v2.md';

const generatorPath = 'packages/teraslice/dist/src/lib/cluster/services/api/v2/docs-tables.js';

/**
 * The sources the generated tables are built from, and the build info of
 * their package. `tsc --build` doesn't rewrite a .js file whose source didn't
 * change, but it updates the build info on every build, so a source is built
 * when the build info is at least as new.
 */
const generatorSources = [
    { src: 'packages/teraslice/src/lib/cluster/services/api/v2', buildInfo: 'packages/teraslice/dist/tsconfig.tsbuildinfo' },
    { src: 'packages/teraslice/src/lib/utils/v2_routes.ts', buildInfo: 'packages/teraslice/dist/tsconfig.tsbuildinfo' },
    { src: 'packages/types/src/teraslice-api-v2.ts', buildInfo: 'packages/types/dist/tsconfig.tsbuildinfo' },
];

const beginNotice = 'auto-generated by `pnpm sync`, manual changes will be lost';

const markerPattern = /<!-- (BEGIN|END) GENERATED ([^:]+?)(?::[^>]*)? -->/g;

/**
 * Replaces the text between each `BEGIN GENERATED <name>` and
 * `END GENERATED <name>` marker with `blocks[name]`. Everything outside the
 * markers is left as it is.
 *
 * Throws if a marker is unmatched or repeated, or if the doc and `blocks`
 * don't have the same names.
 */
export function replaceGeneratedBlocks(doc: string, blocks: Record<string, string>): string {
    let result = '';
    let lastIndex = 0;
    let open: { name: string } | undefined;
    const seen = new Set<string>();

    for (const match of doc.matchAll(markerPattern)) {
        const [marker, kind, name] = match;

        if (kind === 'BEGIN') {
            if (open) throw new Error(`Generated block "${open.name}" has no END marker`);
            if (seen.has(name)) throw new Error(`Generated block "${name}" is in the doc more than once`);
            if (!(name in blocks)) throw new Error(`Generated block "${name}" is in the doc but was not generated`);

            result += doc.slice(lastIndex, match.index);
            result += `<!-- BEGIN GENERATED ${name}: ${beginNotice} -->\n${blocks[name]}\n`;
            open = { name };
            seen.add(name);
        } else {
            if (!open) throw new Error(`Generated block "${name}" has an END marker without a BEGIN`);
            if (open.name !== name) {
                throw new Error(`Generated block "${open.name}" ends with an END marker for "${name}"`);
            }
            open = undefined;
            result += marker;
            lastIndex = match.index + marker.length;
        }
    }

    if (open) throw new Error(`Generated block "${open.name}" has no END marker`);

    const missing = Object.keys(blocks).filter((name) => !seen.has(name));
    if (missing.length) {
        throw new Error(`The doc has no markers for these generated blocks: ${missing.join(', ')}`);
    }

    return result + doc.slice(lastIndex);
}

/**
 * Throws unless the generator is built and no source changed since its
 * package was last built, so the tables aren't generated from an old build.
 */
export function assertGeneratorBuilt(rootDir: string): void {
    const notBuilt = `run \`pnpm build\` before \`pnpm sync\`, it generates ${v2ApiDocPath} from the built teraslice and @terascope/types packages`;

    if (!fs.existsSync(path.join(rootDir, generatorPath))) {
        throw new Error(`${generatorPath} does not exist, ${notBuilt}`);
    }

    for (const { src, buildInfo } of generatorSources) {
        const buildInfoPath = path.join(rootDir, buildInfo);
        if (!fs.existsSync(buildInfoPath)) {
            throw new Error(`${buildInfo} does not exist, ${notBuilt}`);
        }
        const builtAt = fs.statSync(buildInfoPath).mtimeMs;

        const srcPath = path.join(rootDir, src);
        const files = fs.statSync(srcPath).isDirectory()
            ? fs.readdirSync(srcPath).map((file) => path.join(src, file))
            : [src];

        for (const file of files) {
            if (fs.statSync(path.join(rootDir, file)).mtimeMs > builtAt) {
                throw new Error(`${file} changed since it was built, ${notBuilt}`);
            }
        }
    }
}

/**
 * Regenerates the tables in the v2 API doc. Skipped in repos without the doc,
 * since other repos run `ts-scripts sync` too.
 */
export async function syncV2ApiDocs(files: string[]): Promise<void> {
    const rootDir = getRootDir();
    const docPath = path.join(rootDir, v2ApiDocPath);
    if (!fs.existsSync(docPath)) return;

    assertGeneratorBuilt(rootDir);
    const { generateV2DocTables } = await import(
        pathToFileURL(path.join(rootDir, generatorPath)).href
    ) as { generateV2DocTables: () => Record<string, string> };

    const doc = await fs.promises.readFile(docPath, 'utf8');
    try {
        await writeIfChanged(docPath, replaceGeneratedBlocks(doc, generateV2DocTables()));
    } catch (err) {
        throw new Error(`Unable to update ${v2ApiDocPath}: ${(err as Error).message}`);
    }
    files.push(v2ApiDocPath);
}
