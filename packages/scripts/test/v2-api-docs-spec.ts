import 'jest-extended';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { assertGeneratorBuilt, replaceGeneratedBlocks } from '../src/helpers/sync/v2-api-docs.js';

const notice = 'auto-generated by `pnpm sync`, manual changes will be lost';

function block(name: string, content: string): string {
    return `<!-- BEGIN GENERATED ${name}: ${notice} -->\n${content}\n<!-- END GENERATED ${name} -->`;
}

describe('v2 API docs sync', () => {
    describe('->replaceGeneratedBlocks', () => {
        it('should replace only the text between markers', () => {
            const doc = `# Title\n\nintro  with  spacing\n\n${block('A', 'old a')}\n\nmiddle\n${block('B', 'old\nb')}\nend\n`;

            expect(replaceGeneratedBlocks(doc, { A: 'new a', B: 'new b' })).toEqual(
                `# Title\n\nintro  with  spacing\n\n${block('A', 'new a')}\n\nmiddle\n${block('B', 'new b')}\nend\n`
            );
        });

        it('should accept a BEGIN marker without the notice', () => {
            const doc = '<!-- BEGIN GENERATED A -->\n<!-- END GENERATED A -->';

            expect(replaceGeneratedBlocks(doc, { A: 'a' })).toEqual(block('A', 'a'));
        });

        it('should not change a doc that is already up to date', () => {
            const doc = `intro\n${block('A', 'a')}\n`;

            expect(replaceGeneratedBlocks(doc, { A: 'a' })).toEqual(doc);
        });

        it('should throw if a generated block has no markers', () => {
            expect(() => replaceGeneratedBlocks(block('A', 'a'), { A: 'a', B: 'b' }))
                .toThrow('The doc has no markers for these generated blocks: B');
        });

        it('should throw if the doc has a marker that was not generated', () => {
            expect(() => replaceGeneratedBlocks(block('A', 'a'), {}))
                .toThrow('Generated block "A" is in the doc but was not generated');
        });

        it('should throw if a BEGIN marker has no END', () => {
            const doc = `<!-- BEGIN GENERATED A: ${notice} -->\ntext`;

            expect(() => replaceGeneratedBlocks(doc, { A: 'a' })).toThrow('Generated block "A" has no END marker');
        });

        it('should throw if a BEGIN marker is followed by another BEGIN', () => {
            const doc = `<!-- BEGIN GENERATED A -->\n${block('B', 'b')}`;

            expect(() => replaceGeneratedBlocks(doc, { A: 'a', B: 'b' })).toThrow('Generated block "A" has no END marker');
        });

        it('should throw if an END marker has no BEGIN', () => {
            expect(() => replaceGeneratedBlocks('text\n<!-- END GENERATED A -->', { A: 'a' }))
                .toThrow('Generated block "A" has an END marker without a BEGIN');
        });

        it('should throw if an END marker names another block', () => {
            const doc = '<!-- BEGIN GENERATED A -->\n<!-- END GENERATED B -->';

            expect(() => replaceGeneratedBlocks(doc, { A: 'a', B: 'b' }))
                .toThrow('Generated block "A" ends with an END marker for "B"');
        });

        it('should throw if a block is in the doc twice', () => {
            expect(() => replaceGeneratedBlocks(`${block('A', 'a')}\n${block('A', 'a')}`, { A: 'a' }))
                .toThrow('Generated block "A" is in the doc more than once');
        });
    });

    describe('->assertGeneratorBuilt', () => {
        const v2Dir = 'packages/teraslice/src/lib/cluster/services/api/v2';
        const generator = 'packages/teraslice/dist/src/lib/cluster/services/api/v2/docs-tables.js';
        const terasliceBuildInfo = 'packages/teraslice/dist/tsconfig.tsbuildinfo';
        const typesBuildInfo = 'packages/types/dist/tsconfig.tsbuildinfo';
        let rootDir: string;

        function touch(file: string, time: number): void {
            const filePath = path.join(rootDir, file);
            fs.mkdirSync(path.dirname(filePath), { recursive: true });
            fs.writeFileSync(filePath, '');
            fs.utimesSync(filePath, time, time);
        }

        beforeEach(() => {
            rootDir = fs.mkdtempSync(path.join(os.tmpdir(), 'v2-api-docs-'));
            touch(`${v2Dir}/docs-tables.ts`, 1000);
            touch(`${v2Dir}/routes.ts`, 1000);
            touch('packages/teraslice/src/lib/utils/v2_routes.ts', 1000);
            touch('packages/types/src/teraslice-api-v2.ts', 1000);
            touch(generator, 500);
            touch(terasliceBuildInfo, 2000);
            touch(typesBuildInfo, 2000);
        });

        afterEach(() => {
            fs.rmSync(rootDir, { recursive: true, force: true });
        });

        it('should pass when every source is older than its build info', () => {
            expect(() => assertGeneratorBuilt(rootDir)).not.toThrow();
        });

        it('should throw if the generator is not built', () => {
            fs.rmSync(path.join(rootDir, generator));

            expect(() => assertGeneratorBuilt(rootDir))
                .toThrow(`${generator} does not exist, run \`pnpm build\` before \`pnpm sync\``);
        });

        it('should throw if a package was never built', () => {
            fs.rmSync(path.join(rootDir, typesBuildInfo));

            expect(() => assertGeneratorBuilt(rootDir)).toThrow(`${typesBuildInfo} does not exist`);
        });

        it('should throw if a file was added to the v2 folder since the build', () => {
            touch(`${v2Dir}/new-file.ts`, 3000);

            expect(() => assertGeneratorBuilt(rootDir)).toThrow(`${v2Dir}/new-file.ts changed since it was built`);
        });

        it('should throw if a teraslice source changed since the build', () => {
            touch('packages/teraslice/src/lib/utils/v2_routes.ts', 3000);

            expect(() => assertGeneratorBuilt(rootDir))
                .toThrow('packages/teraslice/src/lib/utils/v2_routes.ts changed since it was built');
        });

        it('should throw if the types schemas changed since the build', () => {
            touch('packages/types/src/teraslice-api-v2.ts', 3000);

            expect(() => assertGeneratorBuilt(rootDir))
                .toThrow('packages/types/src/teraslice-api-v2.ts changed since it was built');
        });
    });
});
